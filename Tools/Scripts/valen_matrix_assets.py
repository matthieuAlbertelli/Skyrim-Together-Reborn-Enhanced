"""Generate private #96 Papyrus sources and deterministic silent timing WAVs."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import shutil
import wave

import valen_matrix as corpus
from valen_matrix_plan import build_plan, OWNER
from valen_matrix_audit import audit
from valen_helgen import Plugin, require


def generate(root, before, candidate):
    require(root.resolve().parent==(corpus.ROOT/'_audit/modding').resolve(),'Private session required')
    report=audit(before,candidate)
    plan=build_plan(corpus.read_json(corpus.CORPUS))
    p=Plugin(candidate)
    data=root/'Data'
    source=data/'Source/Scripts'
    source.mkdir(parents=True,exist_ok=True)
    (data/'Scripts').mkdir(exist_ok=True)
    templates=Path(__file__).parent/'valen/matrix'
    qf=report['QF']
    (source/(qf+'.psc')).write_text((templates/'QF.psc.in').read_text('utf-8').replace('@QF@',qf),encoding='utf-8',newline='\n')
    shutil.copyfile(templates/'STRE_ValenHelgenObserver.psc',source/'STRE_ValenHelgenObserver.psc')
    audio=data/'Sound/Voice/STRE_AlternateStart.esp/MaleWarlock'
    audio.mkdir(parents=True,exist_ok=True)
    settings=plan['audio']
    assets=[]
    for r in plan['records']:
        if r['signature']!='INFO' or r['action']=='update':
            continue # Preserve the three #95 WAVs and their timing exactly.
        for number,segment in enumerate(r['segments'],1):
            seconds=max(settings['minimumSeconds'],len(segment)/settings['charactersPerSecond']+settings['paddingSeconds'])
            frames=math.ceil(seconds*settings['sampleRate'])
            name=f"{OWNER[:10]}_{r['topic'][:15]}_{p.ids[r['edid']] & 0xFFFFFF:08x}_{number}.wav".lower()
            path=audio/name
            require(not path.exists(),'Refusing stale/duplicate WAV: '+name)
            with wave.open(str(path),'wb') as wav:
                wav.setparams((settings['channels'],settings['sampleWidth'],settings['sampleRate'],0,'NONE','not compressed'))
                wav.writeframes(bytes(frames*settings['sampleWidth']*settings['channels']))
            assets.append(dict(path=path.relative_to(data).as_posix(),info=r['edid'],number=number,
                               characters=len(segment),frames=frames,bytes=path.stat().st_size,
                               sha256=hashlib.sha256(path.read_bytes()).hexdigest().upper()))
    # No SEQ change is needed: the existing dialogue owner stays SGE with its
    # original identity; the shared narrative quest still starts on acceptance.
    result=dict(success=True,scripts=[qf,'STRE_ValenHelgenObserver'],assets=assets,
                wavCount=len(assets),wavBytes=sum(a['bytes'] for a in assets),
                seq='existing file preserved byte-identically')
    (root/'assets.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return result


def verify(root, before, candidate, *, write_report=True):
    """Read generated bytes, including all PCM samples; never rewrite assets."""
    require(root.resolve().parent==(corpus.ROOT/'_audit/modding').resolve(),'Private session required')
    report=audit(before,candidate)
    plan=build_plan(corpus.read_json(corpus.CORPUS))
    plugin=Plugin(candidate)
    data=root/'Data'
    settings=plan['audio']
    manifest=json.loads((root/'assets.json').read_text('utf-8'))
    expected=[]
    for record in plan['records']:
        if record['signature']!='INFO' or record['action']=='update': continue
        for number,segment in enumerate(record['segments'],1):
            name=f"{OWNER[:10]}_{record['topic'][:15]}_{plugin.ids[record['edid']] & 0xFFFFFF:08x}_{number}.wav".lower()
            relative='Sound/Voice/STRE_AlternateStart.esp/MaleWarlock/'+name
            path=data/relative
            frames=math.ceil(max(settings['minimumSeconds'],len(segment)/settings['charactersPerSecond']+
                                 settings['paddingSeconds'])*settings['sampleRate'])
            with wave.open(str(path),'rb') as wav:
                require((wav.getnchannels(),wav.getsampwidth(),wav.getframerate(),wav.getnframes(),wav.getcomptype())==
                        (1,2,44100,frames,'NONE'),'WAV timing/PCM mismatch: '+relative)
                while samples:=wav.readframes(65536):
                    require(not any(samples),'Non-silent WAV: '+relative)
            expected.append(dict(path=relative,info=record['edid'],number=number,characters=len(segment),
                                 frames=frames,bytes=path.stat().st_size,
                                 sha256=hashlib.sha256(path.read_bytes()).hexdigest().upper()))
    require(manifest['assets']==expected and manifest['wavCount']==len(expected) and
            manifest['wavBytes']==sum(a['bytes'] for a in expected),'Asset manifest mismatch')
    templates=Path(__file__).parent/'valen/matrix'
    qf=report['QF']
    require((data/f'Source/Scripts/{qf}.psc').read_bytes()==
            (templates/'QF.psc.in').read_text('utf-8').replace('@QF@',qf).encode('utf-8'),'QF source mismatch')
    require((data/'Source/Scripts/STRE_ValenHelgenObserver.psc').read_bytes()==
            (templates/'STRE_ValenHelgenObserver.psc').read_bytes(),'Observer source mismatch')
    paths=[a['path'] for a in expected]
    for name in (qf,'STRE_ValenHelgenObserver'):
        pex=data/f'Scripts/{name}.pex'
        require(pex.read_bytes()[:8]==bytes.fromhex('fa57c0de03020001'),'Invalid Skyrim PEX header')
        paths += [f'Source/Scripts/{name}.psc',f'Scripts/{name}.pex']
    result=dict(success=True,wavCount=len(expected),wavBytes=sum(a['bytes'] for a in expected),
                paths=paths,hashes={p:hashlib.sha256((data/p).read_bytes()).hexdigest().upper() for p in paths})
    if write_report:
        (root/'assets-audit.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    return result


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,required=True)
    parser.add_argument('--verify',action='store_true')
    args=parser.parse_args()
    operation=verify if args.verify else generate
    result=operation(args.root,(args.root/'before.esp').read_bytes(),(args.root/'Data/STRE_AlternateStart.esp').read_bytes())
    print(json.dumps({k:v for k,v in result.items() if k not in ('assets','hashes')}))


if __name__=='__main__':
    main()
